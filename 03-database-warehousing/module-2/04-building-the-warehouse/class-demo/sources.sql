-- ============================================================================
-- Source systems: online_store and tills
--
-- Run the whole file against your local SQL Server. It drops and recreates
-- two databases, one per source system, and seeds them with 2025's sales:
--
--   online_store   the web shop: customers, the product catalogue, orders
--   tills          the shops' till system: stores, loyalty members, receipts
--
-- They are two separate systems, so they don't share keys. Run the file again
-- whenever you want clean sources.
-- ============================================================================


-- ============================================================================
-- 1. online_store
-- ============================================================================

USE master;
GO

IF DB_ID('online_store') IS NOT NULL
BEGIN
    ALTER DATABASE online_store SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE online_store;
END
GO

CREATE DATABASE online_store;
GO

USE online_store;
GO

CREATE TABLE customer (
    customer_id INT           NOT NULL PRIMARY KEY,
    first_name  NVARCHAR(50)  NOT NULL,
    last_name   NVARCHAR(50)  NOT NULL,
    email       NVARCHAR(100) NOT NULL,
    city        NVARCHAR(50)  NOT NULL,
    created_at  DATETIME2(0)  NOT NULL,
    updated_at  DATETIME2(0)  NOT NULL   -- last time any column on the row changed
);
GO

-- The product catalogue. list_price is today's price only: the system keeps no
-- history of what a product used to cost.
CREATE TABLE product (
    sku        INT           NOT NULL PRIMARY KEY,
    name       NVARCHAR(100) NOT NULL,
    brand      NVARCHAR(50)  NOT NULL,
    category   NVARCHAR(50)  NOT NULL,
    department NVARCHAR(50)  NOT NULL,
    list_price DECIMAL(10,2) NOT NULL
);
GO

-- ORDER is a reserved word in SQL, so the table is called orders.
CREATE TABLE orders (
    order_id    INT          NOT NULL PRIMARY KEY,
    order_no    VARCHAR(10)  NOT NULL UNIQUE,
    customer_id INT          NOT NULL REFERENCES customer (customer_id),
    order_date  DATE         NOT NULL
);
GO

CREATE TABLE order_line (
    order_id   INT           NOT NULL REFERENCES orders (order_id),
    line_no    INT           NOT NULL,
    sku        INT           NOT NULL REFERENCES product (sku),
    quantity   INT           NOT NULL,
    unit_price DECIMAL(10,2) NOT NULL,              -- the price on the day of the order
    discount   DECIMAL(10,2) NOT NULL DEFAULT 0,    -- coupon money off the whole line
    PRIMARY KEY (order_id, line_no)
);
GO

