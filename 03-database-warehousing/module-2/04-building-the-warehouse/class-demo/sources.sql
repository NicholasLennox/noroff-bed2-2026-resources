USE master;
GO

IF DB_ID('tills') IS NOT NULL
BEGIN
    ALTER DATABASE tills SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE tills;
END
GO

CREATE DATABASE tills;
GO

USE tills;
GO

CREATE TABLE store (
    store_id INT          NOT NULL PRIMARY KEY,
    name     NVARCHAR(50) NOT NULL,
    city     NVARCHAR(50) NOT NULL
);
GO

-- Customers sign up for a loyalty card at the till.
CREATE TABLE loyalty_member (
    card_no   VARCHAR(10)   NOT NULL PRIMARY KEY,
    full_name NVARCHAR(100) NOT NULL,
    email     NVARCHAR(100) NOT NULL,
    city      NVARCHAR(50)  NOT NULL,
    joined_on DATE          NOT NULL
);
GO

-- card_no is NULL when the customer didn't scan a loyalty card.
CREATE TABLE receipt (
    receipt_id INT          NOT NULL PRIMARY KEY,
    receipt_no VARCHAR(10)  NOT NULL UNIQUE,
    sold_at    DATETIME2(0) NOT NULL,
    card_no    VARCHAR(10)  NULL REFERENCES loyalty_member (card_no),
    store_id   INT          NOT NULL REFERENCES store (store_id)
);
GO

-- The tills have no product table of their own. They scan the SKU and store
-- what the customer paid for the line, offers included.
CREATE TABLE receipt_line (
    receipt_id INT           NOT NULL REFERENCES receipt (receipt_id),
    line_no    INT           NOT NULL,
    sku        INT           NOT NULL,
    quantity   INT           NOT NULL,
    line_total DECIMAL(10,2) NOT NULL,
    PRIMARY KEY (receipt_id, line_no)
);
GO

